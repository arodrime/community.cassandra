"""Write the cassandra.yaml properties each Cassandra release accepts.

Usage: python3 tools/gen_yaml_properties.py <dir> [<out file>]
  <dir> holds Config-<release>.java, each release's
  src/java/org/apache/cassandra/config/Config.java (see tools/README.md).

Cassandra 4.0+ refuses a cassandra.yaml whose top-level key is not one of
Config's properties ("Invalid yaml. Please remove properties [...]"): its
public fields, neither static nor transient (Config has no bean setters),
plus the former names its @Replaces annotations still accept (4.1+: the
*_in_ms, *_in_kb... names of the settings renamed with a unit).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "plugins", "plugin_utils", "cassandra_yaml_properties.py")


def _code(src):
    """The source without comments; braces and semicolons in strings made harmless."""
    out, i = [], 0
    while i < len(src):
        if src.startswith("//", i):
            i = src.find("\n", i) if "\n" in src[i:] else len(src)
        elif src.startswith("/*", i):
            i = src.index("*/", i) + 2
        elif src[i] in "\"'":
            j = i + 1
            while src[j] != src[i]:
                j += 2 if src[j] == "\\" else 1
            out.append(src[i:j + 1].replace("{", "(").replace("}", ")").replace(";", ","))
            i = j + 1
        else:
            out.append(src[i])
            i += 1
    return "".join(out)


def _fields(code):
    """The declarations ending with ; in the body of class Config (not in its methods or nested classes)."""
    i = code.index("{", code.index("public class Config")) + 1
    depth, parens, assign, current, fields = 0, 0, False, [], []
    for c in code[i:]:
        if depth == 0:
            if c == "}":
                break
            parens += (c == "(") - (c == ")")
            assign = assign or (c == "=" and not parens)
            if c == ";":
                fields.append("".join(current))
                current, assign = [], False
                continue
            if c == "{":
                depth = 1
                if not assign:  # a method, a nested class or an initializer
                    current = []
                    continue
            current.append(c)
        else:
            depth += (c == "{") - (c == "}")
            if assign:
                current.append(c)
    return fields


def properties(path):
    with open(path) as f:
        code = _code(f.read())
    names = set()
    for field in _fields(code):
        words = re.sub(r"@\w+(\s*\((?:[^()]|\([^()]*\))*\))?", " ", field).split("=")[0].split()
        if "public" not in words or "static" in words or "transient" in words:
            continue
        names.add(words[-1])
        names.update(re.findall(r"@Replaces\s*\([^)]*oldName\s*=\s*\"(\w+)\"", field))
    bad = [n for n in names if not re.match(r"^[a-z0-9_]+$", n)]
    if bad:
        sys.exit("%s: unexpected names %s" % (path, bad))
    return names


def main(src_dir, out=OUT):
    releases = {}
    for name in os.listdir(src_dir):
        m = re.match(r"^Config-(\d+\.\d+)\.(\d+)\.java$", name)
        if m:
            releases.setdefault(m.group(1), {})[int(m.group(2))] = properties(os.path.join(src_dir, name))
    lines = ['# Generated by tools/gen_yaml_properties.py from Config.java of each release: do not edit.',
             '"""The top-level cassandra.yaml properties each Cassandra release accepts (Cassandra 4.0+ refuses',
             'to start on any other: "Invalid yaml. Please remove properties [...]")."""',
             "", "from __future__ import absolute_import, division, print_function", "__metaclass__ = type", "",
             "# series: the last patch release read", "LATEST = {%s}" % ", ".join(
                 '"%s": %d' % (s, max(p)) for s, p in sorted(releases.items())),
             "# series: the properties every patch release read accepts", "ALL = {"]
    some = {}
    for series, patches in sorted(releases.items()):
        missing = [p for p in range(max(patches) + 1) if p not in patches]
        if missing:
            sys.exit("%s: Config.java of %s missing" % (series, ", ".join("%s.%d" % (series, p) for p in missing)))
        everywhere = set.intersection(*patches.values())
        lines.append('    "%s": frozenset((' % series)
        lines += ['        "%s",' % n for n in sorted(everywhere)]
        lines.append("    )),")
        for name in sorted(set.union(*patches.values()) - everywhere):
            accepted = [p for p in sorted(patches) if name in patches[p]]
            ranges = []
            for p in accepted:
                if ranges and ranges[-1][1] == p - 1:
                    ranges[-1][1] = p
                else:
                    ranges.append([p, p])
            some.setdefault(series, []).append((name, ranges))
    lines += ["}", "# series: {property: ((first, last) patch releases that accept it, ...)}, the others", "SOME = {"]
    for series, names in sorted(some.items()):
        lines.append('    "%s": {' % series)
        lines += ['        "%s": (%s),' % (n, " ".join("(%d, %d)," % tuple(r) for r in ranges)) for n, ranges in names]
        lines.append("    },")
    lines.append("}")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    main(*sys.argv[1:])
